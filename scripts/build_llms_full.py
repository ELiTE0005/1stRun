"""Write docs/llms-full.txt: agent.md, the README quickstart, the architecture, the known limits and the share format.

Run it after you edit any of those files. tests/test_agent_files.py fails while the file is stale.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
QUICKSTART = "## Run Your First Check in 5 Minutes"
SITE = "https://firstrun.atharvashah.com/"
REPO = "https://github.com/HighnessAtharva/firstrun/blob/main/"


def _section(markdown: str, heading: str) -> str:
    """One H2 section of a Markdown file, up to the next H2."""
    start = markdown.index(heading)
    nxt = re.search(r"^## ", markdown[start + len(heading):], re.M)
    end = start + len(heading) + nxt.start() if nxt else len(markdown)
    return markdown[start:end].strip() + "\n"


def parts() -> list[tuple[str, str]]:
    """(source URL, text) in the order they appear in llms-full.txt."""
    docs = ROOT / "docs"
    read = lambda p: p.read_text(encoding="utf-8").strip() + "\n"  # noqa: E731
    return [
        (SITE + "agent.md", read(docs / "agent.md")),
        (REPO + "README.md#run-your-first-check-in-5-minutes",
         _section((ROOT / "README.md").read_text(encoding="utf-8"), QUICKSTART)),
        (SITE + "architecture.md", read(docs / "architecture.md")),
        (SITE + "known-limits.md", read(docs / "known-limits.md")),
        (SITE + "share-format.md", read(docs / "share-format.md")),
    ]


def build() -> str:
    head = ("# FirstRun, Full Text for Agents\n\n"
            "> agent.md first, then the README quickstart, the architecture, the known limits and the share format.\n"
            "> Generated by scripts/build_llms_full.py. Edit the source files, not this one.\n")
    blocks = [head]
    for url, text in parts():
        blocks.append(f"\n\n<!-- ===== source: {url} ===== -->\n\n{text}")
    return "".join(blocks)


def main() -> int:
    out = ROOT / "docs" / "llms-full.txt"
    text = build()
    if "--check" in sys.argv:
        current = out.read_text(encoding="utf-8") if out.exists() else ""
        if current != text:
            print(f"{out} is stale. Run: python scripts/build_llms_full.py")
            return 1
        print(f"{out} is current")
        return 0
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
